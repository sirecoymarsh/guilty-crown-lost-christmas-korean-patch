# Keep the verified in-game audio timings when rebuilding the original authoring sheets.
import json
timing_dir=R/'timing-20261124'
original_cues=json.loads((timing_dir/'source-cues.json').read_text(encoding='utf8'))['cues']
reviewed_cues=json.loads((timing_dir/'accepted.json').read_text(encoding='utf8'))['cues']
timings={(a['track'],a['start'],a['end']):(b['start']/1000,b['end']/1000)
         for a,b in zip(original_cues,reviewed_cues) if a['id']==b['id'] and a['track']==b['track']}
rows=[(track,*timings.get((track,round(start*1000),round(end*1000)),(start,end)),source,ko)
      for track,start,end,source,ko in rows]
(R/'data/lyrics.tsv').write_text('\n'.join('|'.join(map(str,x)) for x in rows)+'\n','utf-8')
print('complete authored',len(rows),'cues across',len(set(x[0] for x in rows)),'songs')
