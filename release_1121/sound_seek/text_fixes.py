"""11-24 플레이 중 사용자가 스크린숏으로 짚은 한국어 고침(사용자가 직접 짚은 곳만 — 전수 검수 아님).
patch_seek.py 가 장면 대본을 읽을 때(jp_twin 이 쌍둥이·교차 글을 만들기 전) 바꾼다 → 교차 글에도 그대로 들어간다.
대본 안 글은 cp949, 반각 . , 는 &. &, 로 탈출된 꼴 그대로 적는다. 바꿀 곳은 꼭 한 군데여야 한다.
"""
FIXES = [
    # (장면, 옛 글, 새 글, 사용자 말)
    ('lx0010.nss', '요염할 정도로 하얀 손이', '요염하리만치 새하얀 손이',
     '요염한 정도의 하얀 손- 일본어 번역투이다. 자연스런 한국어로 (原: 艶めかしいほどに白い手が叩く)'),
    # 原: スクルージ「俺に……触るな！」 → //（怯え、恐怖）研究者Ａ「私に触るなぁっ！」 — 같은 말을 연구자가 겁에 질려 되받는다
    # 11-24 사용자 다시: 「연구원의 말은 나한테서 손 치워! 가 낫지 않을까 싶어」(처음 고친 「내… 내게 손대지 마……!」 대신)
    ('lx0101.nss', '「내 몸에 손대지 마아악!」', '「나한테서 손 치워!」',
     '스크루지가 2번 말하는 것처럼 들려 마아악!으로 강조되었지만 실제로 연구원들이 스크루지와 똑같은 대사를 말하는거고 '
     '발화는 공포에 질려서니 소리 지르는 어조가 아니라 두려워하는 어조로'),
    # 原: キャロル「トリガーハッピーだね」(폭주하는 엔드레이브를 보며)
    ('lx0106.nss', '「트리거 해피네」', '「<RUBY TEXT="트리거 해피">쾌락 사격자</RUBY>네」',
     '여기 쾌락 사격자라고 쓰고 트리거 해피를 루비로 넣어'),
]


def apply(name: str, b: bytes) -> bytes:
    for scene, old, new, _ in FIXES:
        if scene.lower() != name.lower():
            continue
        o, n = old.encode('cp949'), new.encode('cp949')
        assert b.count(o) == 1, (scene, old, b.count(o))
        b = b.replace(o, n)
    return b
